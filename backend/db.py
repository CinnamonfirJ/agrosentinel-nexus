class DatabaseError(infra.InfrastructureError): pass

def pg_sql(sql, args):
    if not args: return sql
    sql=sql.replace('%','%%')
    return re.sub(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|\?",lambda m:'%s' if m[0]=='?' else m[0],sql)

class Connection:
    def __init__(self, raw, postgres): self.raw=raw; self.postgres=postgres
    def execute(self, sql, args=()): return self.raw.execute(pg_sql(sql,args) if self.postgres else sql,args)
    def executemany(self, sql, args):
        if not args:return
        cur=self.raw.cursor()
        cur.executemany(pg_sql(sql,args[0]) if self.postgres else sql,args)
        return cur

def make_pool(url):
    pool=ConnectionPool(url,min_size=0,max_size=5,timeout=15,max_idle=60,open=False,check=ConnectionPool.check_connection,
        kwargs={'row_factory':dict_row,'connect_timeout':10,'prepare_threshold':None})
    pool.open()
    return pool

@contextmanager
def pool_connection(pool):
    try:
        with pool.connection() as raw: yield Connection(raw,True)
    except (psycopg.OperationalError,PoolTimeout):
        raise DatabaseError('Neon Postgres is unavailable. Check the saved connection and network. No local database was substituted.') from None

@contextmanager
def connect():
    with _state_lock: pool=_pool
    if pool is not None:
        with pool_connection(pool) as conn: yield conn
    else:
        raw=sqlite3.connect(ROOT/'agro.sqlite3',timeout=30)
        raw.row_factory=sqlite3.Row
        raw.execute('PRAGMA journal_mode=WAL');raw.execute('PRAGMA foreign_keys=ON')
        try:
            with raw: yield Connection(raw,False)
        finally: raw.close()

def execute(sql,args=()):
    with connect() as c:return c.execute(sql,args).rowcount

def rows(sql,args=()):
    with connect() as c:return [dict(r) for r in c.execute(sql,args).fetchall()]

def one(sql,args=()):
    data=rows(sql,args)
    return data[0] if data else None

def initialize_connection(c):
    schema=SCHEMA
    if c.postgres:
        schema=schema.replace('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(' REAL',' DOUBLE PRECISION')
    for statement in schema.split(';'):
        if statement.strip():c.execute(statement)
    if c.postgres:c.execute('ALTER TABLE scans ADD COLUMN IF NOT EXISTS supersedes TEXT')
    elif 'supersedes' not in [r['name'] for r in c.execute('PRAGMA table_info(scans)')]:c.execute('ALTER TABLE scans ADD COLUMN supersedes TEXT')

def initialize():
    with connect() as c:initialize_connection(c)

def begin_exclusive(c, table):
    if table not in ('users','pairing'):raise ValueError('Unsupported lock target.')
    if c.postgres:c.execute('LOCK TABLE '+table+' IN SHARE ROW EXCLUSIVE MODE')
    else:c.execute('BEGIN IMMEDIATE')

def activate(pool,value):
    global _pool
    infra.activate(value)
    with _state_lock:
        previous=_pool;_pool=pool
    if previous is not None:previous.close()

def is_postgres(): return _pool is not None

def setting(key, default=''):
    if key.upper() in os.environ:return os.environ[key.upper()]
    found = one('SELECT value FROM config WHERE key=?',(key,))
    if found:
        try:return vault.decrypt(found['value'].encode()).decode()
        except InvalidToken:raise DatabaseError('Saved settings require the original workspace vault.key. Restore it before continuing.') from None
    return os.environ.get(key.upper(), default)

def set_setting(key, value):
    execute('INSERT INTO config(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value',(key,vault.encrypt(str(value).encode()).decode()))

def password_hash(password):
    salt = secrets.token_hex(16)
    return salt + ':' + hashlib.pbkdf2_hmac('sha256',password.encode(),salt.encode(),600000).hex()

def password_ok(password, stored):
    salt, digest = stored.split(':')
    return secrets.compare_digest(digest, hashlib.pbkdf2_hmac('sha256',password.encode(),salt.encode(),600000).hex())

def session(user_id):
    token=secrets.token_urlsafe(48)
    execute('INSERT INTO sessions VALUES(?,?,?)',(hashlib.sha256(token.encode()).hexdigest(),user_id,time.time()+30*86400))
    return token

def event(scan_id, kind, **payload):
    execute('INSERT INTO events(scan_id,created,kind,payload) VALUES(?,?,?,?)',(scan_id,time.time(),kind,json.dumps(payload)))


